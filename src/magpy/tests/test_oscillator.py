@pytest.mark.parametrize("s12sq, s13sq, s23sq, delta, Dmsq21, Dmsq31, expected_out", TEST_DATA)
def test_oscillator(s12sq: float, s13sq: float, s23sq: float,
                    delta: float, Dmsq21: float, Dmsq31: float,
                    expected_out: torch.Tensor):
    energy_range = [-2.0, -1.0, 1.0, 2.0]

    # We're gonna do every channel
    osc_channels = [NuType.E.value, NuType.Mu.value, NuType.Tau.value]

    final_osc_chans = []
    final_energies = []
    for E_ENERGY in energy_range:
        final_osc_chans.extend([(in_, out) for in_ in osc_channels for out in osc_channels])
        final_energies.extend([E_ENERGY] * (len(osc_channels) ** 2))

    final_osc_chans = torch.tensor(final_osc_chans)
    osc_in = final_osc_chans[:, 0]
    
    osc_out = final_osc_chans[:, 1]

    energies = torch.tensor(final_energies, dtype=torch.float64)


    oscillator = Oscillator(1300, 0.5, 3, 0)
    
    osc_prob = oscillator.calc_probability(s12sq, s13sq, s23sq, delta, Dmsq21, Dmsq31, energies, osc_in, osc_out)

    for i, (exp, pref) in enumerate(zip(expected_out, osc_prob)):
        assert torch.isclose(exp, pref, rtol=1e-8, atol=1e-8), f"For E={energies[i]} {NuType(osc_in[i].item())}->{NuType(osc_out[i].item())}  Expected {exp}, got {pref}"
